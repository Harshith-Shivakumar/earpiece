#!/usr/bin/env node
// Generates earpiece/spec/noise-vectors.json (SPEC 12.3) from fixed keys. Deterministic: running it
// again gives the same file, and test/noise.test.js checks that the committed file still matches.
//
//   node test/gen-noise-vectors.js            write the file
//   node test/gen-noise-vectors.js --print    print to stdout instead

import { createHash } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { HandshakeIK, PROLOGUE, PROTOCOL_NAME, b64url, x25519KeyPair } from '../src/noise.js';

export const VECTORS_PATH = join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'spec', 'noise-vectors.json');

const key = (label) => createHash('sha256').update(`earpiece/2 test vector: ${label}`).digest();
const hex = (b) => Buffer.from(b).toString('hex');

export function buildVectors() {
  const phoneStatic = x25519KeyPair(key('phone static'));
  const phoneEphemeral = x25519KeyPair(key('phone ephemeral'));
  const bridgeStatic = x25519KeyPair(key('bridge static'));
  const bridgeEphemeral = x25519KeyPair(key('bridge ephemeral'));

  const msg1Payload = '{"phone_id":"00000000-0000-0000-0000-000000000001","name":"Test iPhone","pair_secret":"AAAAAAAAAAAAAAAAAAAAAA"}';
  const msg2Payload = '{"ok":true,"name":"Test Bridge","bridge_id":"00000000-0000-0000-0000-0000000000b1"}';

  const phone = new HandshakeIK({ initiator: true, s: phoneStatic, e: phoneEphemeral, rs: bridgeStatic.publicKey });
  const bridge = new HandshakeIK({ initiator: false, s: bridgeStatic, e: bridgeEphemeral });
  const msg1 = phone.writeMessage1(Buffer.from(msg1Payload));
  if (bridge.readMessage1(msg1).toString() !== msg1Payload) throw new Error('msg1 round trip failed');
  const msg2 = bridge.writeMessage2(Buffer.from(msg2Payload));
  if (phone.readMessage2(msg2).toString() !== msg2Payload) throw new Error('msg2 round trip failed');
  if (!phone.handshakeHash.equals(bridge.handshakeHash)) throw new Error('handshake hashes differ');

  const toBridge = [
    '{"type":"hello","last_seq":0,"client":"Test iPhone"}',
    '{"type":"utterance","text":"fix the upload timeouts"}',
    '{"type":"ping"}',
  ];
  const toPhone = [
    '{"type":"welcome","drive_id":null,"cwd":"/Users/test","state":"idle","seq":0,"chat":null,"name":"Test Bridge","bridge_id":"00000000-0000-0000-0000-0000000000b1"}',
    '{"type":"say","seq":1,"text":"Heard: fix the upload timeouts. Starting.","kind":"ack"}',
    '{"type":"pong"}',
  ];
  // Interleaved as a real session would run; each direction has its own nonce counter.
  const transport = [];
  for (let i = 0; i < 3; i++) {
    const c1 = phone.transport.encrypt(Buffer.from(toBridge[i]));
    if (bridge.transport.decrypt(c1).toString() !== toBridge[i]) throw new Error('transport round trip failed');
    transport.push({ direction: 'phone_to_bridge', nonce: i, plaintext: toBridge[i], ciphertext: hex(c1) });
    const c2 = bridge.transport.encrypt(Buffer.from(toPhone[i]));
    if (phone.transport.decrypt(c2).toString() !== toPhone[i]) throw new Error('transport round trip failed');
    transport.push({ direction: 'bridge_to_phone', nonce: i, plaintext: toPhone[i], ciphertext: hex(c2) });
  }

  return {
    format: [
      'Deterministic interop vectors for the Earpiece end-to-end session (SPEC 12.3). Generated by bridge/test/gen-noise-vectors.js.',
      'protocol_name: the Noise protocol name; it is exactly 32 bytes, so the initial h is these ASCII bytes (no hashing). ck starts equal to h.',
      'prologue: ASCII string mixed into h right after initialisation (MixHash). prologue_hex is the same bytes in hex.',
      'All *_private / *_public fields are raw 32-byte X25519 keys in lowercase hex. *_public_b64url are the same public keys as base64url without padding (the encoding used on the wire and in pairing links).',
      'phone = initiator, bridge = responder. Pre-message "<- s": both sides MixHash(bridge_static_public) after the prologue.',
      'Ephemeral keys are fixed here only so the output is reproducible; real sessions generate them randomly per handshake.',
      'msg1_payload / msg2_payload: the UTF-8 JSON payload strings, byte for byte (no trailing newline).',
      'msg1: the full handshake message 1 in hex = e (32) || encrypted s (32 + 16 tag) || encrypted payload (len + 16 tag). Tokens: e, es, s, ss.',
      'msg2: the full handshake message 2 in hex = e (32) || encrypted payload (len + 16 tag). Tokens: e, ee, se.',
      'handshake_hash: h after msg2 has been processed (GetHandshakeHash), hex.',
      'phone_to_bridge_key: the first key from Split() (c1), used by the phone to send and the bridge to receive. bridge_to_phone_key: the second key (c2).',
      'transport: six transport messages in the order they were produced; direction says who sent it, nonce is that direction\'s 64-bit counter (starting at 0 after the handshake), plaintext is the UTF-8 JSON, ciphertext is hex (ChaCha20-Poly1305 with empty associated data; 16-byte tag appended).',
      'ChaChaPoly nonce encoding (Noise spec): 4 zero bytes followed by the counter as 64-bit little-endian. HKDF: HMAC-SHA256 as in Noise spec section 4.3.',
    ],
    protocol_name: PROTOCOL_NAME,
    prologue: PROLOGUE.toString('ascii'),
    prologue_hex: hex(PROLOGUE),
    phone_static_private: hex(phoneStatic.privateKey),
    phone_static_public: hex(phoneStatic.publicKey),
    phone_static_public_b64url: b64url(phoneStatic.publicKey),
    phone_ephemeral_private: hex(phoneEphemeral.privateKey),
    phone_ephemeral_public: hex(phoneEphemeral.publicKey),
    bridge_static_private: hex(bridgeStatic.privateKey),
    bridge_static_public: hex(bridgeStatic.publicKey),
    bridge_static_public_b64url: b64url(bridgeStatic.publicKey),
    bridge_ephemeral_private: hex(bridgeEphemeral.privateKey),
    bridge_ephemeral_public: hex(bridgeEphemeral.publicKey),
    msg1_payload: msg1Payload,
    msg1: hex(msg1),
    msg2_payload: msg2Payload,
    msg2: hex(msg2),
    handshake_hash: hex(phone.handshakeHash),
    phone_to_bridge_key: hex(phone.transport.send.k),
    bridge_to_phone_key: hex(phone.transport.recv.k),
    transport,
  };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = `${JSON.stringify(buildVectors(), null, 2)}\n`;
  if (process.argv.includes('--print')) {
    process.stdout.write(text);
  } else {
    mkdirSync(dirname(VECTORS_PATH), { recursive: true });
    writeFileSync(VECTORS_PATH, text);
    console.log(`wrote ${VECTORS_PATH}`);
  }
}
